/**
 * @file dkmap_tool.cpp
 *
 * Headless builder for the campaign's .dkmap files. It links the game's real map code, so every file
 * goes through the same joining rules, bake and validation as a map saved in the editor, then is read
 * back and loaded the way the game loads it. It opens no window and starts no game.
 *
 * Usage (with -DDARK_KEEP_MAP_TOOL=ON):
 *   dkmap_tool --data E:\Games\Diablo --assets build\assets --levels scripts\dev\dkmap\levels
 *              --out assets\keeper\campaign --doc docs\CAMPAIGN-MAPS.md
 *   dkmap_tool --data E:\Games\Diablo --assets build\assets --check-campaign
 *   dkmap_tool --data E:\Games\Diablo --assets build\assets --fuzz file.dkmap [--runs 2000]
 *
 * A level source is text: `name:`, `tileset:`, `seed:` and `note:` lines, then 40 rows of 40 characters.
 *   # rock   . floor   D door   A arch   E entrance's top-left   V vault's top-left
 *   b barrel   c chest   i brazier (on floor; the object goes on the cell's first world tile)
 * and any number of `prop: <x> <y> <kind>[/<style>]` lines: a prop (MapObjectName, any case) for a click
 * on world tile x, y, as the editor places it: a wall prop snaps to the wall beside that floor. Each must
 * pass the editor's rules, with the props before it standing.
 * A `dress: <theme> [<theme>] [lights=N] [minlights=N] [spacing=N] [scenery=N] [seed=N] [centre=0]` line runs
 * the dressing pass (keeper_dress.hpp) after the prop lines: lights, then scenery for the themes (bones, library,
 * chapel, armoury, torture, prison, tomb, hell). Props and dressing go on the decorated level, as the game
 * builds it. Every level is also built bare, and it fails if its props changed the route or the door and neck
 * numbers.
 *
 * Also:
 *   dkmap_tool --data <mpqs> --assets <assets> --map <source.txt> --out <file.dkmap>   one map, any name
 *   dkmap_tool --data <mpqs> --assets <assets> --selftest                               the file format
 *   --hellfire with any of these: Hellfire's data too (the Nest, the Crypt and their props)
 * Exit code 0 only if every level passed.
 */
